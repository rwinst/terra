const uint8_t* BitmapFont::getGlyph(char c) {
    for (auto& g : kGlyphs) {
        if (g.ch == c) return g.rows;
    }
    char up = static_cast<char>(std::toupper(static_cast<unsigned char>(c)));
    if (up != c) {
        for (auto& g : kGlyphs) {
            if (g.ch == up) return g.rows;
        }
    }
    return nullptr;
}

void BitmapFont::drawText(const std::string& text, int x, int y, int scale, Color color, const RectDrawFn& drawRect) {
    int cursorX = x;
    for (char c : text) {
        const uint8_t* glyph = getGlyph(c);
        if (glyph) {
            for (int row = 0; row < GLYPH_HEIGHT; row++) {
                uint8_t bits = glyph[row];
                for (int col = 0; col < GLYPH_WIDTH; col++) {
                    int bitIndex = GLYPH_WIDTH - 1 - col;
                    if (bits & (1 << bitIndex)) {
                        drawRect(cursorX + col * scale, y + row * scale, scale, scale, color);
                    }
                }
            }
        }
        cursorX += (GLYPH_WIDTH + 1) * scale;
    }
}

int BitmapFont::textWidth(const std::string& text, int scale) {
    return static_cast<int>(text.size()) * (GLYPH_WIDTH + 1) * scale;
}

int BitmapFont::textHeight(int scale) {
    return GLYPH_HEIGHT * scale;
}
